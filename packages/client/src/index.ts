import {
  type ClientSession,
  notificationTargetSchema,
  sessionSchema,
  type Workspace,
} from "@kandamkulathi/contracts/client";

export type Resource<T> =
  | { status: "loading" }
  | { status: "ready"; data: T }
  | { status: "anonymous" | "denied" | "unavailable" | "error" };

export function apiOrigin(value: string, local: boolean): string {
  const url = new URL(value);
  if (
    url.username ||
    url.password ||
    url.search ||
    url.hash ||
    url.pathname !== "/" ||
    !(
      url.protocol === "https:" ||
      (local && url.protocol === "http:" && ["127.0.0.1", "localhost"].includes(url.hostname))
    )
  )
    throw new Error("Invalid API origin");
  return url.origin;
}

/** Uncached, fixed-route request. Never persist session/private responses in browser storage. */
export async function loadSession(
  origin: string,
  local: boolean,
  signal: AbortSignal,
  transport = fetch,
): Promise<Resource<ClientSession>> {
  try {
    const response = await transport(`${apiOrigin(origin, local)}/v1/session`, {
      credentials: "include",
      cache: "no-store",
      redirect: "error",
      signal,
      headers: { Accept: "application/json" },
    });
    if (response.status === 401) return { status: "anonymous" };
    if (response.status === 403) return { status: "denied" };
    if (response.status === 503) return { status: "unavailable" };
    if (!response.ok || !response.headers.get("content-type")?.includes("application/json"))
      return { status: "error" };
    const session = sessionSchema.safeParse(await response.json());
    if (!session.success) return { status: "error" };
    if (Date.parse(session.data.expiresAt) <= Date.now()) return { status: "anonymous" };
    return { status: "ready", data: session.data };
  } catch {
    return { status: "error" };
  }
}

/** A known session deadline revokes local access independently of network revalidation. */
export function watchSessionExpiry(expiresAt: string, onExpired: () => void): () => void {
  const deadline = Date.parse(expiresAt);
  if (!Number.isFinite(deadline)) throw new Error("Invalid session deadline");
  let timer: ReturnType<typeof setTimeout> | undefined;
  const check = () => {
    const remaining = deadline - Date.now();
    if (remaining <= 0) onExpired();
    else timer = setTimeout(check, Math.min(2147483647, remaining));
  };
  check();
  return () => clearTimeout(timer);
}

export function workspaceAccess(session: ClientSession, workspace: Workspace, now = Date.now()) {
  return Date.parse(session.expiresAt) > now && session.workspaces.includes(workspace);
}

/** References are navigation hints; destination APIs must authorize every record. */
export function notificationTarget(input: unknown, authenticated: boolean) {
  const parsed = notificationTargetSchema.safeParse(input);
  if (!parsed.success) return { status: "rejected" } as const;
  return {
    status: authenticated ? "authorization-required" : "session-required",
    target: parsed.data,
  } as const;
}

export function parseNotificationLink(value: string, scheme: string, authenticated: boolean) {
  try {
    const url = new URL(value);
    if (
      !/^kandamkulathi-(local|dev|staging|production)$/.test(scheme) ||
      url.protocol !== `${scheme}:` ||
      url.hostname !== "open" ||
      url.pathname ||
      url.hash ||
      url.username ||
      url.password ||
      [...url.searchParams.keys()].sort().join(",") !== "kind,reference"
    )
      return { status: "rejected" } as const;
    return notificationTarget(
      {
        version: 1,
        kind: url.searchParams.get("kind"),
        reference: url.searchParams.get("reference"),
      },
      authenticated,
    );
  } catch {
    return { status: "rejected" } as const;
  }
}

/** State is generated by the native CSPRNG/server, tied to one attempt and never a payment receipt. */
export function returnGuard(input: {
  redirectUri: string;
  state: string;
  expiresAt: number;
  purpose: "auth" | "payment";
}) {
  const expected = new URL(input.redirectUri);
  if (
    !/^[A-Za-z0-9_-]{32,128}$/.test(input.state) ||
    expected.search ||
    expected.hash ||
    expected.username ||
    expected.password ||
    !(
      /^kandamkulathi-(local|dev|staging|production):$/.test(expected.protocol) ||
      expected.protocol === "https:"
    ) ||
    !Number.isFinite(input.expiresAt)
  )
    throw new Error("Invalid callback attempt");
  let used = false;
  return (value: string, now = Date.now()) => {
    try {
      const url = new URL(value);
      const payload = input.purpose === "auth" ? "code" : "operation_id";
      if (
        used ||
        now >= input.expiresAt ||
        input.expiresAt - now > 10 * 60 * 1000 ||
        url.protocol !== expected.protocol ||
        url.host !== expected.host ||
        url.pathname !== expected.pathname ||
        url.username ||
        url.password ||
        url.hash ||
        [...url.searchParams.keys()].sort().join(",") !== [payload, "state"].sort().join(",") ||
        url.searchParams.get("state") !== input.state
      )
        return { status: "rejected" } as const;
      const reference = url.searchParams.get(payload);
      if (
        !reference ||
        reference.length > 2048 ||
        /\s/.test(reference) ||
        Array.from(reference).some(
          (character) => character.charCodeAt(0) < 32 || character.charCodeAt(0) === 127,
        )
      )
        return { status: "rejected" } as const;
      used = true;
      return { status: "server-verification-required", purpose: input.purpose, reference } as const;
    } catch {
      return { status: "rejected" } as const;
    }
  };
}

export interface SecretStorage {
  get(key: string): Promise<string | null>;
  set(key: string, value: string): Promise<void>;
  remove(key: string): Promise<void>;
}
/** Serialized writes prevent a late token write resurrecting credentials after clear. */
export function credentialVault(
  storage: SecretStorage,
  environment: "local" | "dev" | "staging" | "production",
  purpose: "auth" | "diagnostic" = "auth",
) {
  const key = `kandamkulathi.${environment}.${purpose}`;
  let generation = 0;
  let pending: Promise<unknown> = Promise.resolve();
  const serial = <T>(operation: () => Promise<T>): Promise<T> => {
    const next = pending.then(operation);
    pending = next.catch(() => {});
    return next;
  };
  return {
    read: () => serial(() => storage.get(key)),
    write: (value: string) => {
      const current = generation;
      if (!value || new TextEncoder().encode(value).length > 2048)
        return Promise.reject(new Error("Invalid credential size"));
      return serial(async () => {
        if (current !== generation) throw new Error("Stale credential write");
        await storage.set(key, value);
      });
    },
    clear: () => {
      generation++;
      return serial(() => storage.remove(key));
    },
  };
}
